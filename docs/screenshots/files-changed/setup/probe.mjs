// Settles #601's open questions on the throwaway Hermes: events, checkpoints, diff, one-file restore, stored history.
import { signIn, openPipe } from "./rpc.mjs";
const base = "http://127.0.0.2:26011/";
const s = await signIn(base, "fixture", "fixture-pass-123");
const events = [];
let done;
const pipe = await openPipe(s, "default", (f) => {
  const p = f.params ?? {};
  events.push(p);
  if (p.type === "message.complete") done?.();
});
const show = (label, v) => console.log(`\n== ${label}\n` + JSON.stringify(v, null, 1).slice(0, 2500));
const call = (m, p) => pipe.request(m, p).catch((e) => ({ error: { code: e.code, message: e.message, data: e.data } }));
const turn = async (sid, text) => {
  const t0 = Date.now() / 1000;
  const fin = new Promise((r) => (done = r));
  await pipe.request("prompt.submit", { session_id: sid, profile: "default", text });
  await Promise.race([fin, new Promise((r) => setTimeout(r, 60000))]);
  return t0;
};
show("probe rollback.list", await call("rollback.list", { session_id: "__hermes_chat_probe__" }));
show("probe nosuch", await call("rollback.nosuch", { session_id: "__hermes_chat_probe__" }));
const cfg = await (await fetch(base + "api/config?profile=default", { headers: { cookie: s.cookie } })).json();
show("config checkpoints", { checkpoints: cfg.checkpoints, terminal_backend: cfg.terminal?.backend });
const created = await pipe.request("session.create", { profile: "default", cwd: "/tmp/hermes601/work", cwd_explicit: true });
const sid = created.session_id;
show("session.create", { sid, keys: Object.keys(created), cwd: created.info?.cwd });
show("rollback.diff container check (bad hash)", await call("rollback.diff", { session_id: sid, hash: "__hermes_chat_probe__" }));
const t1 = await turn(sid, "please edit two files");
show("tool events", events.filter((e) => String(e.type).startsWith("tool.")).map((e) => ({ type: e.type, ...e.payload })));
const list1 = await call("rollback.list", { session_id: sid });
show("rollback.list after turn 1 (turn start " + new Date(t1 * 1000).toISOString() + ")", list1);
const h = list1.checkpoints?.[0]?.hash;
const d1 = await call("rollback.diff", { session_id: sid, hash: h });
show("rollback.diff", d1);
await turn(sid, "now create a file");
const list2 = await call("rollback.list", { session_id: sid });
show("rollback.list after create", list2);
const hc = list2.checkpoints?.[0]?.hash;
show("diff before create", await call("rollback.diff", { session_id: sid, hash: hc }));
show("restore created file c.txt", await call("rollback.restore", { session_id: sid, hash: hc, file_path: "c.txt" }));
show("read c.txt", await (await fetch(base + "api/fs/read-text?path=/tmp/hermes601/work/c.txt&profile=default", { headers: { cookie: s.cookie } })).json());
show("restore b.txt to turn-1 checkpoint", await call("rollback.restore", { session_id: sid, hash: h, file_path: "b.txt" }));
show("read b.txt", await (await fetch(base + "api/fs/read-text?path=/tmp/hermes601/work/b.txt&profile=default", { headers: { cookie: s.cookie } })).json());
show("diff after restore", await call("rollback.diff", { session_id: sid, hash: h }));
show("list after restore", await call("rollback.list", { session_id: sid }));
pipe.close();
const p2 = await openPipe(s, "default");
const keySid = (await (await fetch(base + "api/sessions?profile=default", { headers: { cookie: s.cookie } })).json());
show("sessions", (keySid.sessions ?? keySid).slice?.(0, 2).map((x) => ({ id: x.id, cwd: x.cwd })));
const storedId = (keySid.sessions ?? keySid)[0].id;
const res = await p2.request("session.resume", { session_id: storedId, profile: "default", inline_images: false });
show("resume messages (tool rows)", res.messages?.filter((m) => m.role === "tool" || m.tool_calls).map((m) => ({ role: m.role, tool_call_id: m.tool_call_id, name: m.name, args: m.args, context: m.context, display_metadata: m.display_metadata, tool_calls: m.tool_calls, timestamp: m.timestamp })));
show("resume messages (user/assistant times)", res.messages?.filter((m) => m.role !== "tool").map((m) => ({ role: m.role, timestamp: m.timestamp, text: String(m.content ?? m.text ?? "").slice(0, 40) })));
const rest = await (await fetch(base + `api/sessions/${storedId}/messages?profile=default`, { headers: { cookie: s.cookie } })).json();
show("REST rows", (rest.messages ?? rest).map((m) => ({ id: m.id, role: m.role, ts: m.timestamp, dm: m.display_metadata, tool_name: m.tool_name })));
show("list via resumed runtime", await p2.request("rollback.list", { session_id: res.session_id }).catch((e) => e.message));
p2.close();
process.exit(0);
